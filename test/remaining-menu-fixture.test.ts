import { expect, test } from 'bun:test'
test('remaining-menu fixture is opt-in and confines HTTP, sockets and mutations to synthetic state', async () => {
    const normal = await Bun.file(new URL('../index.ts', import.meta.url)).text()
    const fixture = await Bun.file(new URL('./remaining-menu-fixture.tsx', import.meta.url)).text()
    expect(normal).not.toContain('remaining-menu-fixture')
    expect(fixture).toContain('].includes(url.origin)')
    expect(fixture).toContain('External requests are disabled')
    expect(fixture).toContain('<SafeAreaProvider>')
    expect(fixture).toContain('Unsupported synthetic write blocked')
    expect(fixture).toContain('External sockets are disabled')
    expect(fixture).toContain('liveTransport={liveTransport}')
    expect(fixture).toContain('services={thesisServices}')
    expect(fixture).toContain('transport={privacyTransport} exportFile={privacyShare}')
    expect(fixture).toContain('Synthetic membership removed.')
    expect(fixture).toContain('organization.privacy_export.ti.v1')
    expect(fixture).toContain('services={articleServices}')
    expect(fixture).toContain('services={thoughtServices}')
    expect(fixture).toContain('services={systemFixtureServices}')
    expect(fixture).toContain('Synthetic VM inventory handoff')
    expect(fixture).toContain('services={caseFixtureServices}')
    expect(fixture).toContain('services={vmFixtureServices}')
    expect(fixture).toContain('External VM sockets are disabled.')
    expect(fixture).toContain('Synthetic checkout handoff; no browser opened')
    expect(fixture).toContain('proof: async () => ({ proof: \'synthetic-proof\' })')
    expect(fixture).toContain('Synthetic record restored; guest remains missing.')
    expect(fixture).toContain('name: \'fixture-resume\'')
    expect(fixture).toContain('syntheticMissingDetails: true')
    expect(fixture).toContain('path: \'app/page.tsx\'')
    expect(fixture).toContain('Synthetic health check:')
    expect(fixture).toContain('/api/cases/monitoring/merge')
    expect(fixture).toContain('eventTotal: 51')
    expect(fixture).toContain('Synthetic restart accepted.')
    expect(fixture).toContain("url.pathname === '/api/test'")
    expect(fixture).toContain('rerun$/.exec(url.pathname)')
    expect(fixture).toContain('/api/thought/title')
    expect(fixture).toContain('Memory-only recovery')
    expect(fixture).toContain('Emit shared document change')
    expect(fixture).not.toContain('https://hanasand.com')
    expect(fixture).not.toContain('loadSettings')
    expect(fixture).not.toContain('SecureStore')
    expect(fixture).not.toContain('Response.json(')
    expect(fixture).not.toContain('new Response(')
    expect(fixture).toContain('Synthetic response lost after the change was saved.')
    expect(fixture).toContain('globalThis.fetch = syntheticFetch')
})
